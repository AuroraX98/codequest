import fs from 'node:fs/promises';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
const cwd=path.resolve(new URL('..', import.meta.url).pathname);
const ts=(await import(pathToFileURL(cwd+'/node_modules/typescript/lib/typescript.js'))).default;
const React=await import(pathToFileURL(cwd+'/node_modules/react/index.js'));
const {JSDOM}=await import(pathToFileURL(cwd+'/node_modules/jsdom/lib/api.js'));
const assert=(await import('node:assert/strict')).default;
const tmp=await fs.mkdtemp('/tmp/codequest-input-');
await fs.symlink(cwd+'/node_modules',tmp+'/node_modules');
await fs.writeFile(tmp+'/LessonStepFlow.mjs',`import React from 'react'; export default function Flow(p){return React.createElement('button',{onClick:p.onNext},p.text);}`);
const source=await fs.readFile(cwd+'/components/PythonInputLesson.tsx','utf8');
await fs.writeFile(tmp+'/Input.mjs',ts.transpileModule(source,{compilerOptions:{jsx:ts.JsxEmit.ReactJSX,module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText.replace('"./LessonStepFlow"','"./LessonStepFlow.mjs"'));
const dom=new JSDOM('<div id="app"></div>',{url:'https://test.example'});
Object.assign(globalThis,{window:dom.window,document:dom.window.document,localStorage:dom.window.localStorage,IS_REACT_ACT_ENVIRONMENT:true});
const {createRoot}=await import(pathToFileURL(cwd+'/node_modules/react-dom/client.js'));
const Input=(await import(pathToFileURL(tmp+'/Input.mjs'))).default;
const lesson=JSON.parse(await fs.readFile(cwd+'/content/lessons.json','utf8')).find(l=>l.id==='python-input');
const key='codequest-input-owner:python-input';
localStorage.setItem(key,JSON.stringify({part:4,answer:'42',submitted:null}));
let continued=0;const root=createRoot(document.getElementById('app'));
await React.act(async()=>root.render(React.createElement(Input,{lesson,resumeScope:'owner',onContinue:()=>continued++})));
assert.match(document.body.textContent,/does not run Python/);
assert.equal(document.querySelector('input').value,'42');
assert.equal([...document.querySelectorAll('button')].find(b=>b.textContent==='Continue').disabled,true);
await React.act(async()=>document.querySelector('form').dispatchEvent(new dom.window.Event('submit',{bubbles:true,cancelable:true})));
assert.match(document.querySelector('[role=status]').textContent,/returns "42" — a string/);
assert.equal(document.querySelector('[aria-label="Simulated printed output"]').textContent,'42');
await React.act(async()=>[...document.querySelectorAll('button')].find(b=>b.textContent==='Continue').click());
assert.equal(continued,1);
await React.act(async()=>[...document.querySelectorAll('button')].find(b=>b.textContent==='Back').click());
assert.match(document.body.textContent,/print\(topic\)/);
assert.equal(JSON.parse(localStorage.getItem(key)).part,3);
await React.act(async()=>root.unmount());
assert.ok(!lesson.starter.includes('input('));
assert.ok(!lesson.solution.includes('input('));
console.log('PASS input simulation: scoped resume, string42, prompt distinction, continue gating, back, persisted paragraph; no stdin in starter/solution');
await fs.rm(tmp,{recursive:true,force:true});
